# -------------------------------------------------
# Get Personalized Guidance
# -------------------------------------------------

def get_personalized_guidance(disease, symptoms=None, language="English"):

    disease_key = disease.strip().lower()
    language = language.strip().title()

    # Get disease-specific guidance
    disease_guidance = GUIDANCE.get(
        disease_key,
        GUIDANCE["default"]
    )

    # Get requested language
    language_guidance = disease_guidance.get(
        language,
        disease_guidance["English"]
    )

    return {
        "do": language_guidance["do"],
        "dont": language_guidance["dont"],
        "monitor": language_guidance["monitor"]
    }